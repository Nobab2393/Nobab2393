def smooth(a, b, x):
    q = clamp((x - a) / max(1e-6, b - a))
    return q * q * (3 - 2 * q)


def actor(art, who, x, y, h=None, mouth=0.0, night=False, lean=0.0, sess=0.0,
          alpha=1.0):
    """Paste one cast sprite, feet on (x, y), mouth opened by the envelope."""
    sp, origin = sprites.cut(who, night)
    h = h or HEIGHT[who]
    k = h / sp.height
    w = max(1, int(round(sp.width * k)))
    img = sp.resize((w, int(round(h * (1.0 + 0.004 * sess)))), Image.LANCZOS)
    m = MOUTH[who]
    if mouth <= 0.04:
        # the elder's art is drawn mid-sentence; a listener gets a closed mouth back
        cx = (m["x"] - origin[0]) * (img.width / sp.width)
        cy = (m["y"] - origin[1]) * (img.height / sp.height)
        mw = m["w"] * (img.width / sp.width) * 1.06
        mh = m["h"] * (img.width / sp.width) * 0.98
        d = ImageDraw.Draw(img)
        d.ellipse([cx - mw / 2, cy - mh * 0.62, cx + mw / 2, cy + mh * 0.68],
                  fill=(201, 139, 98, 255))
        d.line([(cx - mw * 0.34, cy + mh * 0.05), (cx + mw * 0.34, cy + mh * 0.05)],
               INK_MOUTH + (255,), max(2, int(mh * 0.16)))
    if mouth > 0.04:
        cx = (m["x"] - origin[0]) * (img.width / sp.width)
        cy = (m["y"] - origin[1]) * (img.height / sp.height)
        mw = max(3.0, m["w"] * (img.width / sp.width) * (0.86 + 0.30 * mouth))
        mh = max(2.0, m["h"] * (img.width / sp.width) * (0.18 + 0.82 * mouth))
        d = ImageDraw.Draw(img)
        d.ellipse([cx - mw / 2, cy - mh * 0.42, cx + mw / 2, cy + mh * 0.58],
                  fill=INK_MOUTH + (255,))
    if lean:
        img = img.rotate(lean, resample=Image.BICUBIC, center=(img.width / 2, img.height),
                         expand=False)
    if alpha < 0.999:
        a = img.split()[3].point(lambda v: int(v * alpha))
        img.putalpha(a)
    art.alpha_composite(img, (int(round(x - img.width / 2)), int(round(y - img.height))))


